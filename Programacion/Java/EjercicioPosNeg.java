import java.util.*;
public class EjercicioPosNeg{
	public static void main (String[] args){
		
		int numero = -1;
		
		if(numero > 0){
			System.out.println("El Numero" + numero + "es Positivo");
		}else{
			if(numero == 0){
				System.out.println("El Numero" + numero + "es 0");
			}else{
				System.out.println("El Numero" + numero + "es Negativo");
			}
		}
	}
	
}
